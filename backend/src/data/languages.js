/**
 * Languages for the call feature.
 *
 * Two tiers, deliberately:
 *
 *   CONTENT_LANGS  en, hi, kn — the whole knowledge base (56 entries) exists in
 *                  these, so answers are complete and never machine-made.
 *   CALL_LANGS     the same three plus Tamil, Telugu, Bengali, Marathi,
 *                  Gujarati, Malayalam, Punjabi and Urdu — the call itself
 *                  (greeting, "I did not hear you", the 108 redirect, goodbye)
 *                  works in these, so a user can call and be understood.
 *
 * For a CALL_LANG question the assistant translates the question to English,
 * answers it, and translates the answer back when a Sarvam key is configured
 * (services/translate.js). Without a key it answers in English and says so in
 * the caller's language — it never pretends to have answered in a language it
 * cannot.
 *
 * Speech: the phone speaks with its own text-to-speech engine, which covers far
 * more languages than any server-side voice, so the call does not depend on
 * Polly having a voice for the language.
 */

